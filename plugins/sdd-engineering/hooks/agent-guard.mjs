#!/usr/bin/env node
// agent-guard.mjs — PreToolUse guard for sdd-engineering's own subagents.
//
// Plugin agents cannot carry `hooks:` frontmatter, so this is wired from the plugin's
// hooks/hooks.json for every session and decides by the hook input's `agent_type`:
//   - no agent_type (the main session) or another plugin's agent → allow (exit 0);
//   - sdd-engineering:<agent> → apply that agent's write scope and Bash rules.
// Exit 0 = allow, exit 2 = block (stderr is shown to the agent). FAILS CLOSED for our own
// agents: unparseable input blocks.
//
// Defense in depth, not a sandbox: the Bash check is a denylist over the command text. It
// stops the accidental `sed -i` / `> file` / `git commit`, not a determined bypass. Each
// agent's `tools:` allowlist stays the primary control.

import { readFileSync } from 'node:fs';
import path from 'node:path';

const PLUGIN = 'sdd-engineering';

function block(agent, msg) {
  process.stderr.write(`sdd-engineering agent-guard (${agent}): BLOCKED — ${msg}\n`);
  process.exit(2);
}

let input;
try {
  input = JSON.parse(readFileSync(0, 'utf8'));
} catch {
  // We cannot tell whose call this is; only our own agents must fail closed, and an
  // unparseable payload is not attributable — block to be safe.
  process.stderr.write('sdd-engineering agent-guard: BLOCKED — could not parse hook input (failing closed)\n');
  process.exit(2);
}

const type = typeof input.agent_type === 'string' ? input.agent_type : '';
if (!type.startsWith(`${PLUGIN}:`)) process.exit(0);
const agent = type.slice(PLUGIN.length + 1);

const root = process.env.CLAUDE_PROJECT_DIR || input.cwd || process.cwd();
let config = {};
try {
  config = JSON.parse(readFileSync(path.join(root, '.sdd', 'config.json'), 'utf8'));
} catch {
  /* no config → defaults */
}
const norm = (d, dflt) => (typeof d === 'string' && d.trim() ? d.trim().replace(/^\.\//, '').replace(/\/+$/, '') : dflt);
const SPECS = norm(config.specsDir, 'specs');
const PLANS = norm(config.plansDir, 'docs/plans');
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// ── write scope ────────────────────────────────────────────────────────────
const SCRATCH = /^(\/private)?\/tmp\/|^\/var\/folders\//;
const DENY_ALWAYS = [
  [/^\.sdd\//, 'workflow state (.sdd/) is written only by the plugin scripts the human runs'],
  [/(^|\/)(pnpm-lock\.yaml|package-lock\.json|yarn\.lock|poetry\.lock|Cargo\.lock|go\.sum)$/, 'lock files are generated by the package manager'],
  [/^\.git\//, 'git internals'],
];
const WRITE_ALLOW = {
  'spec-creator': [new RegExp(`^${esc(SPECS)}/[a-z0-9][a-z0-9-]*\\.md$`)],
  'implementation-planner': [new RegExp(`^${esc(PLANS)}/\\d{3}-[a-z0-9-]+\\.plan\\.md$`)],
};
const IMPLEMENTER_DENY = [
  [new RegExp(`^${esc(PLANS)}/`), 'plans are the planner\'s and the human\'s (approval) — report a needed change instead'],
  [new RegExp(`^${esc(SPECS)}/`), 'specs are the spec-creator\'s — report a needed change instead'],
];

function checkWrite() {
  const raw = input?.tool_input?.file_path ?? input?.tool_input?.notebook_path;
  if (typeof raw !== 'string' || raw === '') block(agent, 'no file_path in tool input');
  const abs = path.resolve(root, raw);
  const rel = path.relative(root, abs).split(path.sep).join('/');
  if (rel.startsWith('..') || path.isAbsolute(rel)) {
    // Scratch space outside the project is fine; a project that itself lives under $TMPDIR
    // still gets its write scope (hence the check after the inside-root test).
    if (SCRATCH.test(abs)) return;
    block(agent, `${abs} is outside the repository`);
  }
  for (const [re, why] of DENY_ALWAYS) if (re.test(rel)) block(agent, `${rel}: ${why}`);

  if (agent === 'implementer') {
    for (const [re, why] of IMPLEMENTER_DENY) if (re.test(rel)) block(agent, `${rel}: ${why}`);
    return;
  }
  if (agent === 'spec-creator' && rel === `${SPECS}/README.md`) {
    if (input.tool_name !== 'Edit') block(agent, `${rel} is Edit-only for spec-creator (one index line)`);
    const lines = (t) => String(t ?? '').split('\n').length;
    if (lines(input.tool_input.old_string) > 3 || lines(input.tool_input.new_string) > 3) block(agent, `${rel}: one index entry per Edit`);
    return;
  }
  if (agent === 'implementation-planner') {
    const text = [input.tool_input.content, input.tool_input.new_string].filter((t) => typeof t === 'string').join('\n');
    if (/^\*\*Approved:\*\*/m.test(text)) block(agent, 'a plan may not carry an "**Approved:**" stamp from the planner — approval is the human\'s (plan-admin.mjs)');
  }
  const allow = WRITE_ALLOW[agent];
  if (!allow) block(agent, `${agent} has no write scope`);
  if (!allow.some((re) => re.test(rel))) block(agent, `${rel} is outside the ${agent} write scope (${allow.map((r) => r.source).join(', ')}) — report the change instead`);
}

// ── Bash ───────────────────────────────────────────────────────────────────
const CMD = String.raw`(?:^|[;&|(\x60]|\$\()\s*(?:(?:sudo|env|xargs|command|exec)(?:\s+-\S+)*\s+)*`;
const at = (word) => new RegExp(CMD + String.raw`(?:${word})(?=\s|$|;|&|\|)`);
const ADMIN = [
  [/\bspec-admin\.mjs\b/, 'spec status changes are the human\'s (main session)'],
  [/\bplan-admin\.mjs\b/, 'plan approval is the human\'s (/sdd-engineering:run-plan)'],
  [/\bappend-learning\.mjs\b/, 'learnings are appended only by /sdd-engineering:workflow-retro'],
  [/\bappend-ledger\.mjs\b/, 'the ledger is appended only by /sdd-engineering:workflow-retro'],
  [/\bworkflow-check\.mjs\b[^;&|]*\s--record\b/, 'run history is recorded only by the orchestrator'],
];
const GIT_WRITE = [
  /\bgit\s+(?:(?:-C|-c)\s+\S+\s+|--\S+\s+)*(?:add|commit|push|pull|checkout|switch|reset|restore|stash|apply|am|rebase|merge|cherry-pick|revert|clean|rm|mv|tag|worktree|update-ref|config|init|clone)\b/,
  'git write',
];
const READ_ONLY = [
  [at('rm|rmdir|mv|cp|ln|mkdir|touch|chmod|chown|truncate|dd|install|shred|unlink|patch'), 'filesystem mutation'],
  [at('tee'), 'tee writes files'],
  [new RegExp(CMD + String.raw`(?:sed|perl|ruby)(?:\s[^;&|]*?)?\s(?:-[a-zA-Z]*i|--in-place)`), 'in-place edit'],
  [/\bfind\b[^;&|]*\s(?:-delete|-exec(?:dir)?\s+(?:rm|mv|cp|sed|chmod)\b)/, 'find with a mutating action'],
  GIT_WRITE,
  [/\bgit\s+branch\s+.*-[dDmMcC]\b/, 'git branch mutation'],
  [/\b(?:pnpm|npm|yarn|pip|pip3|uv|poetry|cargo|go)\s+(?:add|install|i|ci|remove|rm|uninstall|up|update|upgrade|link|dlx|publish|get)\b/, 'dependency change'],
  [/\bnpx\b|\bpnpx\b/, 'npx runs arbitrary packages'],
  [/\bgh\s+(?:pr|issue|release|repo|workflow|run)\s+(?:create|merge|comment|edit|close|reopen|review|delete|rerun|cancel|fork)\b/, 'GitHub write'],
  [/\b(?:curl|wget)\b/, 'network access'],
];
const BASH_RULES = {
  'spec-creator': [...ADMIN, ...READ_ONLY],
  'implementation-planner': [...ADMIN, ...READ_ONLY],
  'plan-verifier': [...ADMIN, ...READ_ONLY.filter(([, why]) => why !== 'filesystem mutation')],
  implementer: [...ADMIN, [GIT_WRITE[0], 'git write — the implementer never commits; the human decides'], [/\b(?:curl|wget)\b[^;&|]*\|\s*(?:sh|bash)\b/, 'curl | sh']],
};
const READ_ONLY_REDIRECT = new Set(['spec-creator', 'implementation-planner', 'plan-verifier']);

const stripQuoted = (cmd) => cmd.replace(/'[^']*'/g, "''").replace(/"(?:[^"\\]|\\.)*"/g, '""');

function checkBash() {
  const cmd = input?.tool_input?.command;
  if (typeof cmd !== 'string') block(agent, 'no command in tool input');
  const bare = stripQuoted(cmd);
  if (READ_ONLY_REDIRECT.has(agent)) {
    const redir = bare
      .replace(/\d*>&\d+/g, '')
      .replace(/&?\d*>>?\s*\/dev\/null\b/g, '')
      .replace(/\d*>>?\s*(?:"|')?(?:\/private)?\/tmp\/\S*/g, '')
      .replace(/\d*>>?\s*(?:"|')?\/var\/folders\/\S*/g, '')
      .replace(/\d*>>?\s*(?:"|')?\$\{?TMPDIR\}?\S*/g, '');
    if (/>/.test(redir.replace(/=>|->|<=|>=/g, ''))) block(agent, 'output redirection into a repository file — this agent is read-only in Bash');
  }
  const rules = BASH_RULES[agent];
  if (!rules) block(agent, `unknown agent profile "${agent}"`);
  for (const [re, why] of rules) if (re.test(bare)) block(agent, `${why}: \`${cmd.slice(0, 160)}\``);
}

const tool = input.tool_name;
if (tool === 'Bash') checkBash();
else if (['Edit', 'Write', 'NotebookEdit', 'MultiEdit'].includes(tool)) checkWrite();
process.exit(0);
