#!/usr/bin/env node
// make-channel.mjs — writes a pinned release-channel marketplace (e.g. "stable").
//
// Claude Code has no native release channels: a channel is a second marketplace with its
// own name whose plugin entries are git-subdir sources pinned to release tags
// (`<plugin>--v<version>`). Users pick a channel by adding that marketplace.
//
//   node scripts/make-channel.mjs --url <git url of this repo> [--name <marketplace name>]
//        [--pin <plugin>@<version> ...] [--out <dir>]
//
// Defaults: name "<catalog name>-stable"; every catalog plugin pinned to its highest
// existing release tag unless --pin overrides it; out = channels/stable. The command
// refuses a pin whose tag does not exist, and records each tag's commit SHA so the
// channel is reproducible even if a tag were moved. Exit 0 ok, 1 refused, 2 usage.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const die = (m, c = 1) => {
  process.stderr.write(`make-channel: ${m}\n`);
  process.exit(c);
};
const args = process.argv.slice(2);
const opt = { pins: [] };
for (let i = 0; i < args.length; i++) {
  const v = () => args[++i] ?? die(`${args[i - 1]} needs a value`, 2);
  if (args[i] === '--url') opt.url = v();
  else if (args[i] === '--name') opt.name = v();
  else if (args[i] === '--pin') opt.pins.push(v());
  else if (args[i] === '--out') opt.out = v();
  else die(`unknown argument ${args[i]}`, 2);
}
if (!opt.url) die('--url <git url> is required (e.g. https://github.com/VadymShkarbul/dev-digest-ai-marketplace.git)', 2);

const market = JSON.parse(readFileSync(path.join(ROOT, '.claude-plugin/marketplace.json'), 'utf8'));
const git = (...a) => execFileSync('git', a, { cwd: ROOT, encoding: 'utf8' }).trim();
const tags = git('tag', '--list', '*--v*').split('\n').filter(Boolean);
const semverKey = (v) => v.split('.').map((n) => n.padStart(6, '0')).join('.');
const pinned = Object.fromEntries(opt.pins.map((p) => p.split('@')));

const plugins = market.plugins.map((entry) => {
  const own = tags.filter((t) => t.startsWith(`${entry.name}--v`)).map((t) => t.slice(entry.name.length + 3)).filter((v) => /^\d+\.\d+\.\d+$/.test(v));
  const version = pinned[entry.name] ?? own.sort((a, b) => semverKey(b).localeCompare(semverKey(a)))[0];
  if (!version) die(`${entry.name}: no release tag ${entry.name}--v* exists — release it first`);
  const tag = `${entry.name}--v${version}`;
  if (!tags.includes(tag)) die(`${entry.name}: tag ${tag} does not exist`);
  const sha = git('rev-list', '-n', '1', tag);
  return {
    name: entry.name,
    description: entry.description,
    category: entry.category,
    source: { source: 'git-subdir', url: opt.url, path: String(entry.source).replace(/^\.\//, ''), ref: tag, sha },
  };
});

const name = opt.name ?? `${market.name}-stable`;
const out = path.resolve(ROOT, opt.out ?? 'channels/stable');
mkdirSync(path.join(out, '.claude-plugin'), { recursive: true });
const doc = {
  $schema: market.$schema,
  name,
  description: `Pinned channel of ${market.name}: ${plugins.map((p) => `${p.name}@${p.source.ref.split('--v')[1]}`).join(', ')}. Generated by scripts/make-channel.mjs — do not edit by hand.`,
  owner: market.owner,
  plugins,
};
writeFileSync(path.join(out, '.claude-plugin/marketplace.json'), JSON.stringify(doc, null, 2) + '\n');
process.stdout.write(`${path.relative(ROOT, out) || out}: ${name} → ${plugins.map((p) => p.source.ref).join(', ')}\n`);
